    private void btnCalcularActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnCalcularActionPerformed
        // TODO add your handling code here:
        try {
        Datos d = new Datos();
        Procesos p = new Procesos();

        // 1. Obtención de datos del formulario
        d.setNoches(Integer.parseInt(txtNoches.getText()));
        d.setPrecioNoche(Double.parseDouble(txtPrecio.getText()));
        d.setTipoCliente(cmbTipoCliente.getSelectedItem().toString());

        // 2. Ejecución de cálculos
        double costoBase = p.calcularCostoBase(d);
        double pctCargo = p.obtenerPorcentajeCargo(costoBase);
        double cargoServicio = p.calcularCargoServicio(costoBase);
        double subtotal = p.calcularSubtotal(costoBase, cargoServicio);
        double pctDescuento = p.obtenerPorcentajeDescuento(d.getTipoCliente());
        double descuento = p.calcularDescuento(subtotal, d.getTipoCliente());
        double total = p.calcularTotal(subtotal, descuento);

        // 3. Salida de datos en las cajas de texto de la interfaz
        txtCostoBase.setText(String.format("$%.2f", costoBase));
        txtPorcentajeCargo.setText(String.format("%.0f%%", pctCargo * 100));
        txtCargoServicio.setText(String.format("$%.2f", cargoServicio));
        txtSubtotal.setText(String.format("$%.2f", subtotal));
        txtPorcentajeDescuento.setText(String.format("%.0f%%", pctDescuento * 100));
        txtDescuento.setText(String.format("$%.2f", descuento));
        txtTotal.setText(String.format("$%.2f", total));

    } catch (NumberFormatException ex) 
        {
            javax.swing.JOptionPane.showMessageDialog(Formulario.this, "Por favor ingrese valores numéricos válidos en noches y precio.");
        }
    }//GEN-LAST:event_btnCalcularActionPerformed

